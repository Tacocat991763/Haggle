"""Experiment runner: identical 5-fold splits, OOF + holdout predictions, persistent logging."""
import json
import time
from pathlib import Path

import numpy as np

from .features import ALL_FAMILIES, FeatureBuilder
from .metrics import rmse_log
from .models import MODELS
from .validation import get_data

ROOT = Path(__file__).resolve().parent.parent
EXP = ROOT / "experiments"
RESULTS = EXP / "results.jsonl"
OOF_DIR = EXP / "oof"
_cache = {}


def data():
    if "d" not in _cache:
        _cache["d"] = get_data()
    return _cache["d"]


def load_results():
    if not RESULTS.exists():
        return []
    return [json.loads(l) for l in RESULTS.read_text().splitlines() if l.strip()]


def done(exp_id):
    return any(r["id"] == exp_id for r in load_results())


def best_cv():
    rs = load_results()
    return min((r["cv"] for r in rs), default=float("inf"))


def run(exp_id, model, params=None, families=ALL_FAMILIES, seeds=(0,), note="", keep_raw_skewed=True,
        force=False, verbose=True):
    """Train `model` on each CV fold (averaging `seeds`), write OOF + holdout preds and a results record."""
    if not force and done(exp_id):
        r = next(r for r in load_results() if r["id"] == exp_id)
        if verbose:
            print(f"[skip] {exp_id} cv={r['cv']:.5f}")
        return r
    dev, hold, folds = data()
    y = np.log1p(dev.hours_spent.values)
    oof = np.zeros(len(dev))
    hold_pred = np.zeros(len(hold))
    fold_scores, t_train, t_inf = [], 0.0, 0.0
    prev_best = best_cv()
    for k in range(folds.max() + 1):
        tr, va = folds != k, folds == k
        fb = FeatureBuilder(families, keep_raw_skewed).fit(dev[tr])
        Xtr, Xva, Xho = fb.transform(dev[tr]), fb.transform(dev[va]), fb.transform(hold)
        pv, ph = np.zeros(va.sum()), np.zeros(len(hold))
        for s in seeds:
            t0 = time.time()
            m = MODELS[model](params, fb.cat_cols, seed=s).fit(Xtr, y[tr])
            t1 = time.time()
            pv += m.predict(Xva) / len(seeds)
            ph += m.predict(Xho) / len(seeds)
            t_train += t1 - t0
            t_inf += time.time() - t1
        oof[va] = pv
        hold_pred += ph / (folds.max() + 1)
        fold_scores.append(rmse_log(pv, y[va]))
    cv = rmse_log(oof, y)
    OOF_DIR.mkdir(parents=True, exist_ok=True)
    np.save(OOF_DIR / f"{exp_id}.npy", oof)
    np.save(OOF_DIR / f"{exp_id}_hold.npy", hold_pred)
    rec = dict(id=exp_id, model=model, params=params or {}, families=sorted(families), seeds=list(seeds),
               keep_raw_skewed=keep_raw_skewed, cv=round(cv, 6), folds=[round(f, 5) for f in fold_scores],
               fold_std=round(float(np.std(fold_scores)), 5), train_s=round(t_train, 2), infer_s=round(t_inf, 3),
               prev_best=round(prev_best, 6) if np.isfinite(prev_best) else None,
               improved=bool(cv < prev_best), note=note, n_features=int(Xtr.shape[1]), time=time.strftime("%F %T"))
    with RESULTS.open("a") as f:
        f.write(json.dumps(rec) + "\n")
    write_leaderboard()
    if verbose:
        print(f"{exp_id:40s} cv={cv:.5f} folds={rec['folds']} train={t_train:.1f}s {'*' if rec['improved'] else ''}")
    return rec


def write_leaderboard(n=40):
    rs = sorted(load_results(), key=lambda r: r["cv"])
    lines = ["# Leaderboard (5-fold CV RMSLE on development split, lower is better)", "",
             "Auto-generated by `src/runner.py`. Holdout scores are only reported in `research/notes.md` for confirmed milestones.", "",
             "| rank | id | model | CV RMSLE | fold std | features | seeds | train s | note |",
             "|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rs[:n], 1):
        lines.append(f"| {i} | {r['id']} | {r['model']} | {r['cv']:.5f} | {r['fold_std']:.4f} | "
                     f"{'+'.join(r['families']) or 'raw'} | {len(r['seeds'])} | {r['train_s']} | {r['note']} |")
    (ROOT / "research" / "leaderboard.md").write_text("\n".join(lines) + "\n")
